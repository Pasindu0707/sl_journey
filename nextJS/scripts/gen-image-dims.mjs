// Regenerates src/data/image-dims.ts from the actual JPEGs in public/assets/img/lib.
//
// Run after adding or replacing a library image:  node scripts/gen-image-dims.mjs
//
// The gallery is a CSS `columns` masonry where images are `width:100%` with auto
// height, so without intrinsic dimensions the browser cannot reserve space and
// the grid reflows as each image decodes. Reads the JPEG SOF marker directly to
// avoid taking on a dependency for this.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LIB = join(import.meta.dirname, "..", "public", "assets", "img", "lib");
const OUT = join(import.meta.dirname, "..", "src", "data", "image-dims.ts");

// Frame markers carrying dimensions. Excludes DHT/DAC/RST and the standalone
// markers, which are not frame headers.
const SOF = new Set([
  0xc0, 0xc1, 0xc2, 0xc3, 0xc5, 0xc6, 0xc7,
  0xc9, 0xca, 0xcb, 0xcd, 0xce, 0xcf,
]);

function jpegSize(buf) {
  let off = 2; // skip SOI
  while (off < buf.length) {
    if (buf[off] !== 0xff) throw new Error("bad marker");
    const marker = buf[off + 1];
    const len = buf.readUInt16BE(off + 2);
    if (SOF.has(marker)) {
      return { height: buf.readUInt16BE(off + 5), width: buf.readUInt16BE(off + 7) };
    }
    off += 2 + len;
  }
  throw new Error("no SOF marker");
}

const entries = readdirSync(LIB)
  .filter((f) => f.endsWith(".jpg"))
  .sort()
  .map((f) => {
    const { width, height } = jpegSize(readFileSync(join(LIB, f)));
    return `  "${f.replace(/\.jpg$/, "")}": [${width}, ${height}],`;
  });

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-image-dims.mjs — do not edit by hand.
// Intrinsic pixel dimensions of every image in public/assets/img/lib.

export const IMG_DIMS: Record<string, [number, number]> = {
${entries.join("\n")}
};

/** Intrinsic [width, height], for width/height attributes that prevent CLS. */
export const dims = (name: string): [number, number] => IMG_DIMS[name] ?? [1600, 1067];
`,
  "utf8"
);

console.log(`wrote ${entries.length} entries to src/data/image-dims.ts`);
